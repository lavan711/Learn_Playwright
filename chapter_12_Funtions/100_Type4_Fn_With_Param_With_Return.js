// This is a Type-4 function, which means it has parameters and returns a value.

function sumOfTwoNumbers(a, b) {
    return a + b;
}

let c = sumOfTwoNumbers(4, 5);
console.log(c); 
// Since the sumOfTwoNumbers function takes two parameters a and b, 
// and returns their sum, the variable c will be assigned the value 9.