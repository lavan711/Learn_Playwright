
// Pre Increment
let a = 10;
let b = ++a; // (increment the a by 1)

//Pre increment -> ++a ->. increse the value and then assign.
console.log(b);
console.log(a);

// Post Increment
let a = 10;
let b = a++; // (increment the a by 1)

//Post increment -> a++ ->. assign the value and then increase.
console.log(b); // 10
console.log(a);  // 11


// Post Decrement
let a = 10;
let b = a--; // (decrement the a by 1)
console.log(b); // 10
console.log(a);  // 9

// Pre Decrement
let a = 10;
let b = --a; // (decrement the a by 1)
console.log(b); // 9
console.log(a);  // 9
