//JSON vs JS Objects

//JSON - JavaScript Object Notation
const t_json = {
    "name": "pramod",
    "age": 10
};
console.log(t_json); // { name: 'pramod', age: 10 } because JSON is a string representation of an object, and when we log it, it will be converted to a JavaScript object.

// JS Objects
const t_js = {
    name: "pramod",
    age: 10
};
console.log(t_js); //

